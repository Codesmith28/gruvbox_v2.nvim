--- Dynamic Lualine theme for Gruvbox
Gruvbox.get_lualine_theme = function()
  local colors = get_colors()
  local is_light = vim.o.background == "light"
  local bg_dark = colors.bg_dark
  local bg_buffer = colors.bg_buffer or colors.bg0
  local fg_main = colors.fg1
  local fg_muted = colors.fg4
  local bg_sub = is_light and colors.bg2 or colors.bg1

  local green = colors.green
  local blue = colors.blue
  local orange = colors.orange
  local red = colors.red
  local yellow = colors.yellow
  local purple = colors.purple

  local function mode_style(accent)
    return {
      a = { bg = accent, fg = bg_buffer, gui = "bold" },
      b = { bg = bg_sub, fg = fg_main },
      c = { bg = bg_dark, fg = fg_muted },
      y = { bg = bg_sub, fg = fg_main },
      z = { bg = accent, fg = bg_buffer, gui = "bold" },
    }
  end

  local inactive = { bg = bg_dark, fg = fg_muted }

  return {
    normal = mode_style(green),
    insert = mode_style(blue),
    visual = mode_style(orange),
    replace = mode_style(red),
    command = mode_style(yellow),
    terminal = mode_style(purple),
    inactive = {
      a = vim.tbl_extend("force", inactive, { gui = "bold" }),
      b = inactive,
      c = inactive,
      y = inactive,
      z = inactive,
    },
  }
end

